import { getTable, type Column, type SchemaModel } from '@wardenhq/core';
import { readExampleSql, startPostgres, type TestDatabase } from '@wardenhq/testing';
import pg from 'pg';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { introspect } from '../src/index.js';

const EDGE_CASES = `
  create schema billing;
  create schema misc;
  create schema warden;

  create table warden.audit_log (id bigint primary key);

  create type billing.currency as enum ('USD', 'EUR', 'GBP');

  create table billing.invoices (
    company_id   bigint not null references public.companies (id),
    number       int not null,
    currency     billing.currency not null,
    accepted     billing.currency[] not null default '{}',
    tags         text[],
    total_cents  int not null,
    total        numeric generated always as (total_cents / 100.0) stored,
    external_ref text,
    primary key (company_id, number)
  );
  comment on table billing.invoices is 'Customer invoices';
  comment on column billing.invoices.total is 'Computed from total_cents';
  create unique index invoices_external_ref_key on billing.invoices (external_ref) include (tags);
  create unique index invoices_lower_ref_key on billing.invoices (lower(external_ref));
  create unique index invoices_partial_key on billing.invoices (number) where currency = 'USD';

  create table billing.invoice_lines (
    company_id     bigint not null,
    invoice_number int not null,
    line           int not null,
    primary key (company_id, invoice_number, line),
    foreign key (invoice_number, company_id) references billing.invoices (number, company_id)
  );

  create table misc.events (
    id  bigint generated by default as identity,
    at  timestamptz not null
  ) partition by range (at);
  create table misc.events_2026 partition of misc.events
    for values from ('2026-01-01') to ('2027-01-01');

  create table misc.no_pk (value text, dropped int);
  alter table misc.no_pk drop column dropped;
`;

let db: TestDatabase;
let pool: pg.Pool;

beforeAll(async () => {
  db = await startPostgres({
    sql: [await readExampleSql('basic/schema.sql'), EDGE_CASES],
  });
  pool = new pg.Pool({ connectionString: db.connectionString });
}, 120_000);

afterAll(async () => {
  await pool?.end();
  await db?.stop();
});

const table = (model: SchemaModel, name: string, schema?: string) => {
  const t = getTable(model, name, schema);
  if (!t) throw new Error(`table ${schema ?? 'public'}.${name} not found`);
  return t;
};
const column = (model: SchemaModel, tableName: string, name: string, schema?: string) => {
  const c = table(model, tableName, schema).columns.find((col) => col.name === name);
  if (!c) throw new Error(`column ${tableName}.${name} not found`);
  return c;
};

describe('introspect', () => {
  it('matches the example schema snapshot', async () => {
    expect(await introspect(pool)).toMatchSnapshot();
  });

  it('only reads the requested schemas and never the warden schema', async () => {
    const model = await introspect(pool, { schemas: ['billing', 'misc', 'warden'] });
    expect(model.tables.map((t) => `${t.schema}.${t.name}`)).toEqual([
      'billing.invoice_lines',
      'billing.invoices',
      'misc.events',
      'misc.no_pk',
    ]);
  });

  it('returns composite primary keys in key order', async () => {
    const model = await introspect(pool, { schemas: ['billing'] });
    expect(table(model, 'invoice_lines', 'billing').primaryKey).toEqual([
      'company_id',
      'invoice_number',
      'line',
    ]);
  });

  it('returns foreign keys with positionally matched columns, across schemas', async () => {
    const model = await introspect(pool, { schemas: ['billing'] });
    expect(table(model, 'invoices', 'billing').foreignKeys).toEqual([
      {
        name: 'invoices_company_id_fkey',
        columns: ['company_id'],
        references: { schema: 'public', name: 'companies', columns: ['id'] },
      },
    ]);
    expect(table(model, 'invoice_lines', 'billing').foreignKeys[0]).toMatchObject({
      columns: ['invoice_number', 'company_id'],
      references: { schema: 'billing', name: 'invoices', columns: ['number', 'company_id'] },
    });
  });

  it('includes only full, non-expression unique keys and excludes INCLUDE columns', async () => {
    const model = await introspect(pool, { schemas: ['billing'] });
    expect(table(model, 'invoices', 'billing').uniqueKeys).toEqual([['external_ref']]);
  });

  it('describes enum, array, and generated columns', async () => {
    const model = await introspect(pool, { schemas: ['billing'] });
    expect(column(model, 'invoices', 'currency', 'billing')).toMatchObject({
      dataType: 'currency',
      isArray: false,
      enum: { schema: 'billing', name: 'currency' },
    });
    expect(column(model, 'invoices', 'accepted', 'billing')).toMatchObject({
      dataType: 'currency',
      formattedType: 'billing.currency[]',
      isArray: true,
      hasDefault: true,
      enum: { schema: 'billing', name: 'currency' },
    });
    expect(column(model, 'invoices', 'tags', 'billing')).toMatchObject({
      dataType: 'text',
      formattedType: 'text[]',
      isArray: true,
      nullable: true,
    });
    expect(column(model, 'invoices', 'total', 'billing')).toMatchObject({
      generated: true,
      hasDefault: true,
      comment: 'Computed from total_cents',
    });
    expect(table(model, 'invoices', 'billing').comment).toBe('Customer invoices');
    expect(model.enums).toEqual([
      { schema: 'billing', name: 'currency', values: ['USD', 'EUR', 'GBP'] },
    ]);
  });

  it('reports declared lengths and numeric precision, including for array elements', async () => {
    await db.exec(`
      create table misc.sized (
        code char(3), title varchar(80), labels varchar(20)[], body text, plain varchar,
        price numeric(12, 2), ratio numeric(5), amount numeric, weight float8
      )`);
    try {
      const model = await introspect(pool, { schemas: ['misc'] });
      const pick = ({ maxLength, precision, scale }: Column) => ({ maxLength, precision, scale });
      const columns = table(model, 'sized', 'misc').columns;
      expect(Object.fromEntries(columns.map((c) => [c.name, pick(c)]))).toEqual({
        code: { maxLength: 3 },
        title: { maxLength: 80 },
        labels: { maxLength: 20 },
        body: {},
        plain: {},
        price: { precision: 12, scale: 2 },
        ratio: { precision: 5, scale: 0 },
        amount: {},
        weight: {},
      });
    } finally {
      await db.exec('drop table misc.sized');
    }
  });

  it('marks defaults that draw from a sequence', async () => {
    await db.exec(`
      create sequence misc.counter;
      create table misc.defaults (
        a serial, b bigint default nextval('misc.counter'), c timestamptz default now(),
        d uuid default gen_random_uuid(), e int generated by default as identity, f int
      )`);
    try {
      const model = await introspect(pool, { schemas: ['misc'] });
      const columns = table(model, 'defaults', 'misc').columns;
      expect(columns.map((c) => [c.name, c.hasDefault, c.sequenceDefault])).toEqual([
        ['a', true, true],
        ['b', true, true],
        ['c', true, undefined],
        ['d', true, undefined],
        ['e', true, undefined],
        ['f', false, undefined],
      ]);
    } finally {
      await db.exec('drop table misc.defaults; drop sequence misc.counter');
    }
  });

  it('includes enums from other schemas when a column references them', async () => {
    await db.exec(`create table misc.prices (currency billing.currency not null)`);
    try {
      const model = await introspect(pool, { schemas: ['misc'] });
      expect(model.enums.map((e) => `${e.schema}.${e.name}`)).toEqual(['billing.currency']);
    } finally {
      await db.exec('drop table misc.prices');
    }
  });

  it('reports partitioned parents, hides partitions, and skips dropped columns', async () => {
    const model = await introspect(pool, { schemas: ['misc'] });
    expect(table(model, 'events', 'misc')).toMatchObject({ kind: 'partitioned' });
    expect(getTable(model, 'events_2026', 'misc')).toBeUndefined();
    expect(column(model, 'events', 'id', 'misc')).toMatchObject({
      identity: 'byDefault',
      hasDefault: true,
    });
    expect(table(model, 'no_pk', 'misc')).toMatchObject({
      primaryKey: [],
      columns: [{ name: 'value' }],
    });
  });
});
